#!/usr/bin/env node
// SPDX-License-Identifier: AGPL-3.0-only
// Loombre :: scripts/docs/collect-screenshots.mjs
//
// Addendum A, lane D1 (STATE.md "## Addendum A", deliverable 9). Every page
// in the docs suite is free to drop a `[SCREENSHOT: description]` placeholder
// where a real screenshot belongs but doesn't exist yet (docs/install/*.md
// already uses this convention — see docs/install/macos.md,
// docs/install/windows.md). This script walks every published doc, collects
// every placeholder, and writes them into ONE page
// (docs/reference/screenshots.md) so the outstanding list is visible and
// trackable in the built site instead of silently scattered across pages.
//
// This is a TRACKING tool, not a gate: an outstanding screenshot is expected
// pre-launch (real screenshots land as a separate, later pass once the UI
// surfaces they depict are frozen) — this script always exits 0. It runs as
// a docs:build pre-step (scripts/docs/build.mjs) so the generated page is
// present as real Markdown before `vitepress build` renders the site.
//
// Placeholder convention: a single line (or inline span) of the exact form
// `[SCREENSHOT: <description>]` — case-sensitive on the leading token,
// matching every existing usage in docs/install/*.md.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { walkDocs } from "./lib/walk-md.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..", "..");
const DOCS_ROOT = join(REPO_ROOT, "docs");
const OUTPUT_REL = "reference/screenshots.md";
const OUTPUT_PATH = join(DOCS_ROOT, OUTPUT_REL);

const PLACEHOLDER_RE = /\[SCREENSHOT:\s*([^\]]+)\]/g;

const files = walkDocs(DOCS_ROOT).filter(({ rel }) => rel !== OUTPUT_REL);

/** @type {{ rel: string, lineNo: number, description: string }[]} */
const found = [];

for (const { full, rel } of files) {
  const content = readFileSync(full, "utf8");
  const lines = content.split("\n");
  lines.forEach((line, idx) => {
    for (const match of line.matchAll(PLACEHOLDER_RE)) {
      found.push({ rel, lineNo: idx + 1, description: match[1].trim() });
    }
  });
}

found.sort((a, b) => (a.rel === b.rel ? a.lineNo - b.lineNo : a.rel.localeCompare(b.rel)));

const byPage = new Map();
for (const item of found) {
  if (!byPage.has(item.rel)) byPage.set(item.rel, []);
  byPage.get(item.rel).push(item);
}

const lines = [
  "# Outstanding screenshots",
  "",
  "<!-- GENERATED by scripts/docs/collect-screenshots.mjs — do not edit by hand;",
  "     re-run `pnpm docs:build` (or the script directly) to refresh. -->",
  "",
  "This page is generated by scanning every published guide for " +
    "`[SCREENSHOT: …]` placeholders — the convention the install guides " +
    "established (see `docs/install/macos.md`, `docs/install/windows.md`). " +
    "It exists so a real screenshot pass has a single checklist instead of " +
    "scattered TODOs, and so an outstanding placeholder is visible, not " +
    "silently forgotten. It is **not** a build failure — outstanding " +
    "screenshots are an expected pre-launch state.",
  "",
  `**${found.length} placeholder(s) across ${byPage.size} page(s)** as of the last \`pnpm docs:build\` run.`,
  "",
];

if (found.length === 0) {
  lines.push("None outstanding — every placeholder has been replaced with a real screenshot.");
} else {
  for (const [rel, items] of byPage) {
    lines.push(`## \`${rel}\``, "");
    for (const item of items) {
      lines.push(`- line ${item.lineNo}: ${item.description}`);
    }
    lines.push("");
  }
}

mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
writeFileSync(OUTPUT_PATH, lines.join("\n") + "\n");

console.log(
  `collect-screenshots: ${found.length} placeholder(s) across ${byPage.size} page(s) -> docs/${OUTPUT_REL}`,
);
process.exit(0);
