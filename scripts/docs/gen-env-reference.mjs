// generator for the Operator Guide's environment variable reference,
// reading packages/shared/src/settings-registry.ts's SETTINGS_REGISTRY
// directly. Supersedes this file's original stub.
//
// SCOPE ADJUSTMENT (orchestrator, this session): this generator was
// originally lane S3's deliverable ("operator env-ref gen hook"); the
// orchestrator reassigned it to this lane to avoid two lanes editing
// scripts/docs/build.mjs concurrently. Lane S3 still OWNS
// packages/shared/src/settings-registry.ts's content (this script only
// reads it, never writes it — same read-only relationship
// gen-settings-reference.mjs has).
//
// RUNTIME: invoked via `tsx`, not plain `node` — see this file's sibling
// gen-settings-reference.mjs for the full reasoning (no committed dist/
// dependency, no build-ordering assumption, always current against
// concurrent registry edits).
//
// TWO SECTIONS, per the orchestrator's explicit brief:
//   1. Every scope:'env-only' entry — bootstrap/lockout-boundary
//      configuration with NO settings-screen equivalent at all (A2).
//   2. The env-PIN variable for every scope:'ui' entry that carries one
//      (A8) — operators need the full pin list even though these ARE also
//      editable from the settings screen, because setting the variable
//      overrides and locks whatever the screen shows. This is the
//      operator-facing half of the same fact gen-settings-reference.mjs's
//      "Can be locked" note states from the admin side — cross-linked by
//      anchor (both scripts import the same slugify()/titleFor() from
//      lib/settings-titles.mjs, so the anchors always agree).
//
// REGISTER: Operator Guide audience — technical self-hoster, "no source-
// code references" (that's Developer Guide territory). Registry
// descriptions carry real source-code citations in parentheses (e.g.
// "(apps/server/src/main.ts's resolveTrustProxySetting)"); this generator
// strips those via lib/settings-format.mjs's stripSourceCodeRefs() rather
// than reproducing them verbatim (contrast with gen-settings-reference.mjs,
// which DOES reproduce descriptions verbatim per explicit instruction —
// that instruction was scoped to the admin/UI-consistency page, not this
// one, and this page's audience rule is stricter about source references).
// Spec citations ("docs/PLAN.md §..." / "docs/PLAYBACK.md §...") are left
// intact — those aren't source code and are exactly the kind of
// traceability a technical operator benefits from.
//
// NOT COMMITTED: regenerated by every `pnpm docs:build` run, same as
// gen-settings-reference.mjs's output — see that script's header for the
// no-drift rationale. Secrets and pure-infra variables that aren't part of
// the settings registry at all (POSTGRES_PASSWORD, LOOMBRE_JWT_SECRET —
// grep-confirmed absent from SETTINGS_REGISTRY) are NOT invented here;
// this page points to installers/docker/loombre.env.example for those,
// same as the stub it replaces did.

import { writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SETTINGS_REGISTRY } from "../../packages/shared/src/settings-registry.js";
import { ENV_CATEGORY_ORDER, ENV_CATEGORY_TITLES, titleFor, slugify } from "./lib/settings-titles.mjs";
import { formatDefaultWithTiers, stripSourceCodeRefs } from "./lib/settings-format.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..", "..");
const OUTPUT_PATH = join(REPO_ROOT, "docs", "ops", "env-reference.md");
const ENV_EXAMPLE_PATH = join(REPO_ROOT, "installers", "docker", "loombre.env.example");

const envOnlyEntries = SETTINGS_REGISTRY.filter((entry) => entry.scope === "env-only");
const pinnedUiEntries = SETTINGS_REGISTRY.filter((entry) => entry.scope === "ui" && entry.envVar);

/** @param {string} heading e.g. "####" — callers control nesting depth so
 *  this function has no opinion about where it sits in the document. */
function renderEnvOnly(entry, heading) {
  const what = stripSourceCodeRefs(entry.description);
  const lines = [`${heading} \`${entry.envVar}\``, "", `**${titleFor(entry.key)}.** ${what}`, ""];
  lines.push(`- **Default when unset:** ${formatDefaultWithTiers(entry)}`);
  if (entry.caution) lines.push(`- **Caution:** ${entry.caution}`);
  lines.push("");
  return lines.join("\n");
}

function renderPin(entry, heading) {
  const anchor = slugify(titleFor(entry.key));
  const what = stripSourceCodeRefs(entry.description);
  const lines = [
    `${heading} \`${entry.envVar}\``,
    "",
    `Pins **[${titleFor(entry.key)}](/admin-guide/settings-reference#${anchor})** ` +
      `(\`${entry.key}\`) to a fixed value — set this and the admin settings screen ` +
      `shows the setting as controlled by the environment, read-only; any value stored ` +
      `from the settings screen is preserved but ignored until the variable is unset again.`,
    "",
    what,
    "",
  ];
  lines.push(`- **Default when unset:** ${formatDefaultWithTiers(entry)} (or whatever was last saved from the settings screen)`);
  if (entry.caution) lines.push(`- **Caution:** ${entry.caution}`);
  lines.push("");
  return lines.join("\n");
}

const byCategory = new Map();
for (const entry of envOnlyEntries) {
  if (!byCategory.has(entry.category)) byCategory.set(entry.category, []);
  byCategory.get(entry.category).push(entry);
}
const knownCategories = new Set(ENV_CATEGORY_ORDER);
const unmappedCategories = [...byCategory.keys()].filter((c) => !knownCategories.has(c));
if (unmappedCategories.length > 0) {
  console.warn(
    `gen-env-reference: WARNING — categor${unmappedCategories.length === 1 ? "y" : "ies"} not in ENV_CATEGORY_ORDER ` +
      `(scripts/docs/lib/settings-titles.mjs): ${unmappedCategories.join(", ")}. Appended with a generic heading.`,
  );
}
const categoryOrder = [...ENV_CATEGORY_ORDER.filter((c) => byCategory.has(c)), ...unmappedCategories];

const exampleExists = existsSync(ENV_EXAMPLE_PATH);

const lines = [
  "# Environment variable reference",
  "",
  "<!-- GENERATED by scripts/docs/gen-env-reference.mjs from",
  "     packages/shared/src/settings-registry.ts (SETTINGS_REGISTRY) — do not",
  "     edit by hand, edits are overwritten on the next `pnpm docs:build`. -->",
  "",
  "Every environment variable Loombre's settings registry recognizes, in two groups:",
  "",
  "1. **[Bootstrap & lockout-boundary variables](#bootstrap-lockout-boundary-variables)** " +
    "— no settings-screen equivalent at all. Some are needed before the database " +
    "(and therefore any UI-stored setting) is even reachable; the rest are configuration " +
    "an admin could otherwise lock themselves out with if it were editable at runtime.",
  "2. **[Environment pins for admin-editable settings](#environment-pins-for-admin-editable-settings)** " +
    "— these DO have a settings-screen equivalent (see the " +
    "[Admin Guide's settings reference](/admin-guide/settings-reference)); setting the " +
    "variable overrides and locks whatever's in the database or the screen.",
  "",
  "Assumption: variable names and defaults below are Loombre's own environment-variable " +
    "convention as read by the server/worker processes directly — this is independent of " +
    "*how* you set them (systemd `Environment=`, a Docker Compose env file, a shell export " +
    "before running from source, etc.); see [Install](/install/) for the mechanism that " +
    "applies to your install path.",
  "",
  "## Bootstrap & lockout-boundary variables",
  "",
];

for (const category of categoryOrder) {
  const title = ENV_CATEGORY_TITLES[category] ?? category;
  lines.push(`### ${title}`, "");
  for (const entry of byCategory.get(category)) {
    lines.push(renderEnvOnly(entry, "####"));
  }
}

lines.push("## Environment pins for admin-editable settings", "");
for (const entry of pinnedUiEntries) {
  lines.push(renderPin(entry, "###"));
}

lines.push(
  "## Secrets and other bootstrap variables not in this list",
  "",
  exampleExists
    ? "A few bootstrap variables — notably `POSTGRES_PASSWORD` and `LOOMBRE_JWT_SECRET` — are " +
      "secrets rather than settings and aren't part of the settings registry this page is " +
      "generated from. The full, accurate, hand-maintained list of every variable Loombre's " +
      "Docker Compose distribution reads (including these) lives in " +
      "[`installers/docker/loombre.env.example`](https://github.com/Loombre/Loombre/blob/main/installers/docker/loombre.env.example); " +
      "[docs/install/docker.md](/install/docker) walks the two you cannot skip."
    : "See `installers/docker/loombre.env.example` in the repository (not found in this " +
      "checkout at generation time — check the path is still correct) for secrets " +
      "(`POSTGRES_PASSWORD`, `LOOMBRE_JWT_SECRET`) and other bootstrap variables outside the " +
      "settings registry this page is generated from.",
  "",
);

mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
writeFileSync(OUTPUT_PATH, lines.join("\n").replace(/\n{3,}/g, "\n\n") + "\n");

console.log(
  `gen-env-reference: wrote ${envOnlyEntries.length} bootstrap var(s) + ${pinnedUiEntries.length} pin(s) -> docs/ops/env-reference.md`,
);
